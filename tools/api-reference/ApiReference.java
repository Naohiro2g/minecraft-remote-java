import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Properties;
import java.util.Set;
import java.util.stream.Collectors;
import javax.lang.model.SourceVersion;
import javax.lang.model.element.ElementKind;
import javax.lang.model.element.ExecutableElement;
import javax.lang.model.element.Modifier;
import javax.lang.model.element.TypeElement;
import javax.lang.model.util.ElementFilter;
import javax.tools.ToolProvider;
import jdk.javadoc.doclet.Doclet;
import jdk.javadoc.doclet.DocletEnvironment;
import jdk.javadoc.doclet.Reporter;

/** Generates the Java client reference using the JDK's Java parser, without extra dependencies. */
public final class ApiReference implements Doclet {

    private static final String PACKAGE = "club.code2create.mcremote.client.";
    private Path output;
    private Path metadata;

    public static void main(String[] args) throws IOException {
        var tool = ToolProvider.getSystemDocumentationTool();
        try (var manager = tool.getStandardFileManager(null, Locale.JAPANESE, StandardCharsets.UTF_8);
                var sources = Files.walk(Path.of(args[0]))) {
            var files = manager.getJavaFileObjectsFromPaths(
                    sources.filter(path -> path.toString().endsWith(".java")).sorted().toList());
            var options = List.of("-quiet", "-public", "-encoding", "UTF-8", "--release", "21",
                    "-classpath", args[3], "--metadata", args[1], "--output", args[2]);
            if (!tool.getTask(null, manager, null, ApiReference.class, options, files).call()) {
                throw new IllegalStateException("API reference generation failed");
            }
        }
    }

    @Override
    public void init(Locale locale, Reporter reporter) {}

    @Override
    public String getName() {
        return "Minecraft Remote Java reference";
    }

    @Override
    public SourceVersion getSupportedSourceVersion() {
        return SourceVersion.RELEASE_21;
    }

    @Override
    public Set<? extends Option> getSupportedOptions() {
        return Set.of(pathOption("--metadata", path -> metadata = path),
                pathOption("--output", path -> output = path));
    }

    private static Option pathOption(String name, java.util.function.Consumer<Path> setter) {
        return new Option() {
            public int getArgumentCount() { return 1; }
            public String getDescription() { return name; }
            public Kind getKind() { return Kind.OTHER; }
            public List<String> getNames() { return List.of(name); }
            public String getParameters() { return "path"; }
            public boolean process(String option, List<String> arguments) {
                setter.accept(Path.of(arguments.getFirst()));
                return true;
            }
        };
    }

    @Override
    public boolean run(DocletEnvironment environment) {
        try {
            Properties descriptions = new Properties();
            try (var reader = Files.newBufferedReader(metadata, StandardCharsets.UTF_8)) {
                descriptions.load(reader);
            }
            List<TypeElement> types = ElementFilter.typesIn(environment.getIncludedElements()).stream()
                    .filter(type -> type.getQualifiedName().toString().startsWith(PACKAGE))
                    .sorted(Comparator.comparing(ApiReference::order)).toList();
            StringBuilder text = new StringBuilder("<!-- Generated by ./gradlew generateApiReference. -->\n");
            text.append("# JavaクライアントAPIリファレンス（試作）\n\n")
                    .append("このcheckoutで使える公開APIをJavaソースから生成した一覧です。公開Maven版はまだありません。\n")
                    .append("シグネチャ・recordの要素・enumの選択肢は実装から読み、説明は日本語metadataから付けています。\n\n")
                    .append("[最初の実行](../README.md) · [作例](java-examples_ja.md) · ")
                    .append("[対応範囲と検証](compatibility_ja.md) · [Protocol API一覧](https://mc-remote.com/api/)\n\n")
                    .append("同じインスタンスを複数threadから同時に使わないでください。world操作の座標は建築原点から相対、")
                    .append("`setOrigin`は絶対座標です。サーバーは操作を権限・範囲・処理上限などで拒否することがあります。\n\n")
                    .append("## 用途から探す\n\n| 用途 | Javaの入口 |\n| --- | --- |\n")
                    .append("| 接続・pairing・終了 | [builder](#api-MinecraftRemote-builder)、[Builder](#type-MinecraftRemote.Builder)、[close](#api-MinecraftRemote-close) |\n")
                    .append("| 建築原点 | [setOrigin](#api-MinecraftRemote-setOrigin)、[buildContext](#api-MinecraftRemote-buildContext) |\n")
                    .append("| ブロックを置く・読む | [setBlock](#api-MinecraftRemote-setBlock)、[setBlocks](#api-MinecraftRemote-setBlocks)、[getBlock](#api-MinecraftRemote-getBlock) |\n")
                    .append("| プレイヤーの位置と向き | [getPlayerPose](#api-MinecraftRemote-getPlayerPose)、[setPlayerPose](#api-MinecraftRemote-setPlayerPose) |\n")
                    .append("| 看板・particle | [setSign](#api-MinecraftRemote-setSign)、[getSign](#api-MinecraftRemote-getSign)、[updateSignLine](#api-MinecraftRemote-updateSignLine)、[spawnParticle](#api-MinecraftRemote-spawnParticle) |\n")
                    .append("| チャット・イベント | [postToChat](#api-MinecraftRemote-postToChat)、[pollEvents](#api-MinecraftRemote-pollEvents) |\n")
                    .append("| ブロック名・stateの発見 | [getCatalog](#api-MinecraftRemote-getCatalog) |\n")
                    .append("| エラーの理由 | [RemoteCallException](#type-RemoteCallException) |\n\n")
                    .append("## 型から探す\n\n| 用途 | 型 |\n| --- | --- |\n");
            for (TypeElement type : types) {
                String name = name(type);
                text.append("| ").append(description(descriptions, name)).append(" | [`")
                        .append(name).append("`](#type-").append(name).append(") |\n");
            }
            for (TypeElement type : types) {
                String name = name(type);
                text.append("\n<a id=\"type-").append(name).append("\"></a>\n\n## `")
                        .append(name).append("`\n\n").append(description(descriptions, name)).append("\n\n");
                if (type.getKind() == ElementKind.RECORD) {
                    text.append("```java\nrecord ").append(name).append("(");
                    if (!type.getRecordComponents().isEmpty()) {
                        text.append("\n    ").append(type.getRecordComponents().stream()
                                    .map(component -> shortType(component.asType()) + " " + component.getSimpleName())
                                    .collect(Collectors.joining(",\n    ")))
                                .append("\n");
                    }
                    text.append(")\n```\n\n");
                    if (!type.getRecordComponents().isEmpty()) {
                        text.append("各要素は同名のアクセサー（例: `値.要素名()`）で取得できます。\n\n");
                    }
                }
                var constants = type.getEnclosedElements().stream()
                        .filter(element -> element.getKind() == ElementKind.ENUM_CONSTANT)
                        .map(element -> "`" + element.getSimpleName() + "`").toList();
                if (!constants.isEmpty()) {
                    text.append("選択肢: ").append(String.join("、", constants)).append("。\n\n");
                }
                for (var field : ElementFilter.fieldsIn(type.getEnclosedElements())) {
                    if (field.getModifiers().contains(Modifier.PUBLIC) && field.getConstantValue() != null) {
                        text.append("定数: `").append(field.getSimpleName()).append(" = ")
                                .append(field.getConstantValue()).append("`。\n\n");
                    }
                }
                Map<String, List<ExecutableElement>> methods = new LinkedHashMap<>();
                for (var method : ElementFilter.methodsIn(type.getEnclosedElements())) {
                    if (method.getModifiers().contains(Modifier.PUBLIC)
                            && environment.getDocTrees().getPath(method) != null) {
                        methods.computeIfAbsent(method.getSimpleName().toString(), key -> new ArrayList<>()).add(method);
                    }
                }
                for (var entry : methods.entrySet()) {
                    String key = name + "." + entry.getKey();
                    text.append("<a id=\"api-").append(name).append("-").append(entry.getKey())
                            .append("\"></a>\n\n### `").append(entry.getKey()).append("`\n\n")
                            .append(description(descriptions, key)).append("\n\n```java\n");
                    for (var method : entry.getValue()) {
                        text.append(signature(method)).append("\n");
                    }
                    text.append("```\n\n");
                    if (descriptions.containsKey(key + ".wire")) {
                        text.append("対応するProtocol API: `").append(descriptions.getProperty(key + ".wire"))
                                .append("`。\n\n");
                    }
                }
                String source = environment.getDocTrees().getPath(type).getCompilationUnit().getSourceFile().getName();
                String fileName = Path.of(source).getFileName().toString();
                text.append("[実装](../src/main/java/club/code2create/mcremote/client/")
                        .append(fileName).append(")\n");
            }
            Files.createDirectories(output.getParent());
            Files.writeString(output, text, StandardCharsets.UTF_8);
            return true;
        } catch (IOException | IllegalArgumentException exception) {
            throw new IllegalStateException(exception);
        }
    }

    private static String description(Properties descriptions, String key) {
        String result = descriptions.getProperty(key);
        if (result == null) throw new IllegalArgumentException("Missing Japanese description: " + key);
        return result;
    }

    private static String name(TypeElement type) {
        return type.getQualifiedName().toString().substring(PACKAGE.length());
    }

    private static String order(TypeElement type) {
        String name = name(type);
        return name.equals("MinecraftRemote") ? "0" : name.equals("MinecraftRemote.Builder") ? "1" : "2" + name;
    }

    private static String shortType(Object value) {
        return value.toString().replace(PACKAGE, "").replace("java.lang.", "")
                .replace("java.util.", "").replace("java.time.", "");
    }

    private static String signature(ExecutableElement method) {
        String parameters = method.getParameters().stream()
                .map(parameter -> shortType(parameter.asType()) + " " + parameter.getSimpleName())
                .collect(Collectors.joining(", "));
        if (method.isVarArgs()) parameters = parameters.replaceFirst("\\[\\](?= [^,]+$)", "...");
        String thrown = method.getThrownTypes().isEmpty() ? "" : " throws "
                + method.getThrownTypes().stream().map(ApiReference::shortType).collect(Collectors.joining(", "));
        return (method.getModifiers().contains(Modifier.STATIC) ? "static " : "")
                + shortType(method.getReturnType()) + " " + method.getSimpleName() + "(" + parameters + ")" + thrown;
    }
}
